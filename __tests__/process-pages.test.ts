import { describe, expect, it } from 'vitest'
import {
  buildPageContext, INDEX_END, INDEX_START, committedPages, linkLawRules, renderPagesIndex,
  renderProcessPage, validatePageSet, validatePagesIndexDoc, validateProcessPages,
} from '@/lib/processPages'

// open-processes/pages/ ↔ corpus drift gate: every canonical record renders as a committed
// Markdown page (scripts/generate-process-pages.ts), and this gate fails on any divergence —
// a drifted page, a stale page, a missing page, or a drifted README index block. Same
// byte-identity doctrine as lib/__tests__/stepRankings.test.ts and __tests__/situations.test.ts.

describe('open-processes/pages', () => {
  const ctx = buildPageContext()

  it('the committed pages and README index pass the drift gate byte-for-byte', () => {
    expect(validateProcessPages()).toEqual([])
  })

  it('renders one page per canonical record, named by the record slug', () => {
    const committed = committedPages()
    expect(committed.size).toBe(ctx.sources.length)
    for (const source of ctx.sources) {
      expect(committed.has(`${source.slug}.md`), `${source.slug}.md`).toBe(true)
    }
  })

  it('keeps local fees and completion checks in their named country section', () => {
    const source = ctx.sources.find((s) => s.record.id === 'form_001')!
    const page = renderProcessPage(source, ctx)
    const country = page.slice(page.indexOf('### United States'), page.indexOf('### United Kingdom'))
    expect(country).toContain('$500')
    expect(country).toContain('Verify:')
    const uk = page.slice(page.indexOf('### United Kingdom'), page.indexOf('### India'))
    expect(uk).not.toContain('$500')
  })

  it('every page carries the generated-file header naming its source record', () => {
    for (const [name, content] of committedPages()) {
      const slug = name.slice(0, -3)
      expect(content.startsWith(`<!-- Generated by scripts/generate-process-pages.ts from open-processes/${slug}.json`), name).toBe(true)
      expect(content).toContain(`[\`open-processes/${slug}.json\`](../${slug}.json)`)
    }
  })

  it('links inline law-rule citations to committed rule cards and leaves unknown ids plain', () => {
    const linked = linkLawRules('due March 1 (law rule us-de.franchise-tax-annual-report)', ctx)
    expect(linked).toBe(
      'due March 1 (law rule [us-de.franchise-tax-annual-report](../../open-law/US-DE/us-de-franchise-tax-annual-report.json))',
    )
    const unknown = 'see law rule zz.not-a-committed-rule here'
    expect(linkLawRules(unknown, ctx)).toBe(unknown)
  })

  it('links every id in a comma-separated "law rules" citation list', () => {
    const linked = linkLawRules('(law rules ee.social-tax-rate-and-monthly-return, ee.unemployment-insurance-premiums)', ctx)
    expect(linked).toContain('[ee.social-tax-rate-and-monthly-return](../../open-law/EE/ee-social-tax-rate-and-monthly-return.json)')
    expect(linked).toContain('[ee.unemployment-insurance-premiums](../../open-law/EE/ee-unemployment-insurance-premiums.json)')
  })

  it('situation pages lead with their trigger; chains list their constituents in order', () => {
    const situation = ctx.sources.find((s) => !s.taskIds && s.record.kind === 'situation')!
    expect(renderProcessPage(situation, ctx)).toContain('**Trigger:**')
    const chain = ctx.sources.find((s) => s.taskIds)!
    const page = renderProcessPage(chain, ctx)
    expect(page).toContain('## Processes in order')
    for (const id of chain.taskIds!) {
      const slug = ctx.slugById.get(id)!
      expect(page).toContain(`(${slug}.md)`)
    }
  })
})

describe('process-pages validators (failure modes)', () => {
  const rendered = new Map([['a.md', 'page a\n'], ['b.md', 'page b\n']])

  it('fails on a drifted page', () => {
    const committed = new Map([['a.md', 'page a (stale)\n'], ['b.md', 'page b\n']])
    expect(validatePageSet(committed, rendered).join(';')).toContain('a.md: drifted')
  })

  it('fails on a missing page and on a stale extra page', () => {
    const committed = new Map([['a.md', 'page a\n'], ['c.md', 'orphan\n']])
    const errors = validatePageSet(committed, rendered).join(';')
    expect(errors).toContain('b.md: missing')
    expect(errors).toContain('c.md: stale')
  })

  it('fails when the README index markers are missing or the block drifted', () => {
    const block = `${INDEX_START}\n\nindex\n\n${INDEX_END}`
    expect(validatePagesIndexDoc('no markers', block).join(';')).toContain('missing the generated index markers')
    expect(validatePagesIndexDoc(`${INDEX_START}\n\nstale\n\n${INDEX_END}`, block).join(';')).toContain('drifted')
    expect(validatePagesIndexDoc(`prose\n\n${block}\n\nmore prose`, block)).toEqual([])
  })

  it('the index block groups records by kind with computed counts', () => {
    const ctx = buildPageContext()
    const block = renderPagesIndex(ctx.sources)
    const processes = ctx.sources.filter((s) => !s.taskIds && s.record.kind === 'process').length
    const situations = ctx.sources.filter((s) => !s.taskIds && s.record.kind === 'situation').length
    const chains = ctx.sources.filter((s) => s.taskIds).length
    expect(block).toContain(`${processes} processes, ${situations} situations, ${chains} chains.`)
    expect(block.startsWith(INDEX_START)).toBe(true)
    expect(block.endsWith(INDEX_END)).toBe(true)
  })
})
