import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))
const inventory = read('coverage/startup-task-inventory.json')
const sources = read(inventory.sources).sources
const records = new Map(read('open-processes/catalog.json').processes.map((slug) => {
  const record = read(`open-processes/${slug}.json`)
  return [record.id, { slug, record }]
}))
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
const mapped = inventory.needs.filter((need) => need.processIds.length > 0 && need.processIds.every((id) => records.has(id))).length
const ordinary = [...records.values()].filter(({ record }) => !record.taskIds)
const processes = ordinary.filter(({ record }) => record.kind === 'process').length
const situations = ordinary.length - processes
const lines = [
  '<!-- Generated by scripts/generate-startup-coverage.mjs from coverage/startup-task-inventory.json. -->', '',
  '# Startup task coverage', '', inventory.scope, '', inventory.measurement, '',
  `Mapped guide entry points: **${mapped} / ${inventory.needs.length} named needs**. The catalog has ${processes} process guides and ${situations} situation guides.`, '',
  'Use each guide’s applicability, completion checks and approval requirements. Operational drafts require the stated specialist review before regulated or professional work proceeds.', '',
]
for (const domain of inventory.domains) {
  const needs = inventory.needs.filter((need) => need.domain === domain.id)
  lines.push(`## ${domain.name}`, '', '| Need | Applies when | Guides |', '| --- | --- | --- |')
  for (const need of needs) {
    const guides = need.processIds.map((id) => {
      const target = records.get(id)
      if (!target) throw new Error(`${need.id}: unknown guide ${id}`)
      return `[${target.record.title.replace(/\[/g, '\\[').replace(/\]/g, '\\]')}](../open-processes/pages/${target.slug}.md)`
    })
    lines.push(`| ${cell(need.need)} | ${cell(need.appliesWhen)} | ${cell(guides.join(' · ') || 'Gap: no guide mapped')} |`)
  }
  lines.push('')
}
lines.push('## Specialist boundaries', '', '| Scope | Required next step |', '| --- | --- |')
for (const boundary of inventory.specialistBoundaries) lines.push(`| ${cell(boundary.scope)} | ${boundary.status.replaceAll('-', ' ')} |`)
lines.push('', 'The regulated-market entry guide provides a scoping and approval path. Detailed clinical, financial-service, aviation, defense and other sector protocols need their own qualified workstreams. Country-specific workflow coverage remains tracked in [the law-layer coverage file](../open-law/workflow-coverage.json).', '',
  '## Sources and editorial evidence', '',
  'Source jurisdiction describes the cited material. A source from one country does not establish requirements elsewhere. The source register records page checks; the guides identify professional decisions separately.', '',
  '| Source | Context | Checked |', '| --- | --- | --- |',
  ...sources.map((source) => `| [${cell(source.title)}](${source.url}) | ${cell(source.jurisdictionOrContext)} | ${source.checkedOn} |`), '',
  '[Expansion audit](startup-expansion-audit.json) · [Fictional examples and approval gates](fixtures/startup-lifecycle-coverage.json) · [Full guide index](../open-processes/README.md#record-pages)', '')
const output = lines.join('\n')
const file = path.join(root, 'coverage/STARTUP-TASKS.md')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) throw new Error('coverage/STARTUP-TASKS.md is stale; rerun scripts/generate-startup-coverage.mjs')
} else fs.writeFileSync(file, output)
