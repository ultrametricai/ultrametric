// Re-triage of two issue #378 candidates under the founder decisions of 2026-10-23 (one-shot,
// committed with the wave it records, like radar-settle-2026-10-15-19.ts).
//
// The corrected 2026-10-15..19 triage routed Proa (domain:proa.so) and replica-skill
// (domain:opusjake.ai) to needs-human on ranking-fit: Proa because the frontend-frameworks
// definition then scoped JavaScript frameworks, replica-skill because its strongest lexical
// match (ai-code-review) was incidental. The founder resolved both on issue #378:
//
//   - frontend-frameworks is multi-language; Proa (a Rust web framework) is admitted there.
//   - replica-skill belongs in agent-skills (its own lexical match: skill, skills, agent).
//
// This script replays the mechanical criteria checks (docs surface, shipped product, popularity
// trip-wires, agentic surface) for each candidate against its decided arena, live, and records
// the dispositions in a dated report. The founder decision supplies the arena; every other
// check result is whatever the fetches showed. Reasons carry the decision note verbatim so the
// report reads standalone; statuses stay the mechanical outcome (a needs-human here is resolved
// by the founder decision recorded on issue #378, not by rewriting the status).
//
// Usage: pnpm tsx rankings-engine/scripts/radar-retriage-issue-378.ts
import fs from 'node:fs'
import path from 'node:path'
import { readCategories, writeJson } from '../paths'
import { REPORTS_DIR, RadarReportSchema, type RadarCandidate } from './vendor-radar'
import { TriageReportSchema, buildTriageMarkdown, realTriageIo, triageCandidate, type Disposition } from './radar-triage'

const DECISIONS: Record<string, { fromReport: string; arena: string; note: string; extraEvidence: string[] }> = {
  'domain:proa.so': {
    fromReport: '2026-10-16.json',
    arena: 'frontend-frameworks',
    note: 'founder decision 2026-10-23 (issue #378): the frontend-frameworks arena covers UI frameworks in any implementation language; bring Proa up there. Agentic/docs surface verified by hand where the mechanical probe checks only /llms.txt.',
    extraEvidence: [
      'https://proa.so/llms-full.txt — HTTP 200, text/plain; charset=utf-8, markdown H1 "Proa documentation corpus" (fetched 2026-10-23); the docs site also serves .md mirrors of each page (e.g. https://proa.so/docs/index.md)',
      'https://proa.so/docs/agents — HTTP 200, "Agent setup" documentation for coding agents working in Proa projects (fetched 2026-10-23)',
      'https://github.com/Proa-Labs/proa — Apache-2.0, created 2026-09-12 (GitHub API, fetched 2026-10-23); install: cargo install proa-cli --locked (https://proa.so/docs)',
    ],
  },
  'domain:opusjake.ai': {
    fromReport: '2026-10-18.json',
    arena: 'agent-skills',
    note: 'founder decision 2026-10-23 (issue #378): bring replica-skill up in agent-skills (the arena its own lexical match nominated); the ai-code-review match was incidental. A needs-human routing from the popularity trip-wires is resolved by this recorded human review.',
    extraEvidence: [],
  },
}

async function main(): Promise<void> {
  const categories = readCategories()
  const existingArenas = new Set(categories.map((c) => c.id))
  const arenaDefinitions = new Map<string, string>(categories.map((c) => [c.id, c.description]))
  const io = realTriageIo()
  const dispositions: Disposition[] = []

  for (const [key, decision] of Object.entries(DECISIONS)) {
    const report = RadarReportSchema.parse(JSON.parse(fs.readFileSync(path.join(REPORTS_DIR, decision.fromReport), 'utf8')))
    const original = report.candidates.find((c) => c.key === key)
    if (!original) throw new Error(`candidate ${key} not found in ${decision.fromReport}`)
    // The founder decision names the arena: keep only its lexical match (recorded in the
    // original scan) so checkRankingFit verifies that match rather than the incidental one.
    const decided: RadarCandidate = {
      ...original,
      matchedArenas: original.matchedArenas.filter((m) => m.arena === decision.arena),
    }
    if (decided.matchedArenas.length === 0) throw new Error(`${key} has no recorded lexical match for ${decision.arena}`)
    const d = await triageCandidate(decided, existingArenas, io, arenaDefinitions)
    dispositions.push({ ...d, reason: `${d.reason}; ${decision.note}`, evidence: [...d.evidence, ...decision.extraEvidence] })
  }

  const triage = TriageReportSchema.parse({
    _comment:
      'Generated by rankings-engine/scripts/radar-retriage-issue-378.ts — issue #378 founder decisions of 2026-10-23 applied to the Proa and replica-skill candidates from the corrected 2026-10-15..19 triage. Statuses are the mechanical criteria outcomes against the decided arenas; the founder decision recorded in each reason (and on issue #378) is the human review that resolves a needs-human routing. Bring-up still runs the standard scoped engine pipeline.',
    generatedAt: new Date().toISOString(),
    policy: 'policies/AGENT_POLICY.md#vendor-radar-candidate-approval',
    dispositions,
  })
  const out = path.join(REPORTS_DIR, '2026-10-23-issue-378-retriage.json')
  writeJson(out, triage)
  const markdown = buildTriageMarkdown(triage)
  fs.writeFileSync(out.replace(/\.json$/, '.md'), markdown + '\n')
  console.log(markdown)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
