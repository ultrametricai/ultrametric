// Needs-human issue builder for the recurring generator workflows (vendor-radar daily,
// yc-coverage weekly). Maintainer decision 2026-10-23: a generator files an issue only when a
// human call is needed. The triage's auto-approved and skipped dispositions ride the scan PR's
// body and the committed triage report; only the needs-human rows (founder affiliation,
// star-velocity anomaly — the dispositions radar-triage.ts reserves for a human) become an
// issue, labeled `founder-call` by the workflow so they are findable.
//
// The CLI writes --out ONLY when the triage holds at least one needs-human disposition, so the
// workflows' existing "body file exists => file the issue" gate turns into "a human call
// exists => file the issue". A triage with zero needs-human rows writes nothing.
//
//   pnpm tsx rankings-engine/scripts/needs-human-issue.ts \
//     --triage reports/vendor-radar/<date>-triage.json --out /tmp/needs-human.md \
//     --generator vendor-radar
import fs from 'node:fs'
import path from 'node:path'
import { TriageReportSchema, type Disposition, type TriageReport } from './radar-triage'

export function needsHumanRows(triage: TriageReport): Disposition[] {
  return triage.dispositions.filter((d) => d.status === 'needs-human')
}

// The issue body, or null when the triage routed nothing to a human (no issue to file).
export function buildNeedsHumanIssue(triage: TriageReport, generator: string): string | null {
  const rows = needsHumanRows(triage)
  if (rows.length === 0) return null
  const date = triage.generatedAt.slice(0, 10)
  const lines: string[] = []
  lines.push(`## ${generator}: candidates needing a human call — ${date}`)
  lines.push('')
  lines.push(
    `${rows.length} of ${triage.dispositions.length} triaged candidate${triage.dispositions.length === 1 ? '' : 's'} ` +
      `need${rows.length === 1 ? 's' : ''} a human decision (criteria: \`${triage.policy}\`). ` +
      'Auto-approved and skipped dispositions are on the scan PR body and in the committed triage report; nothing here is actioned autonomously.',
  )
  lines.push('')
  lines.push('| candidate | arena | criterion | reason |')
  lines.push('| --- | --- | --- | --- |')
  for (const d of rows) {
    lines.push(`| [${d.name}](${d.url}) | ${d.arena ? `\`${d.arena}\`` : ''} | ${d.criterion ?? ''} | ${d.reason} |`)
  }
  const withEvidence = rows.filter((d) => d.evidence.length > 0)
  if (withEvidence.length > 0) {
    lines.push('')
    lines.push('### Evidence')
    lines.push('')
    for (const d of withEvidence) {
      lines.push(`- **${d.name}**`)
      for (const e of d.evidence) lines.push(`  - ${e}`)
    }
  }
  lines.push('')
  lines.push(`_Generated by the ${generator} workflow (rankings-engine/scripts/needs-human-issue.ts). Full dispositions: the dated triage JSON under \`reports/vendor-radar/\`._`)
  return lines.join('\n')
}

// --- CLI ----------------------------------------------------------------------------------------

function main(argv: string[]): void {
  const arg = (flag: string): string | undefined => {
    const i = argv.indexOf(flag)
    return i === -1 ? undefined : argv[i + 1]
  }
  const triagePath = arg('--triage')
  const out = arg('--out')
  const generator = arg('--generator')
  if (!triagePath || !out || !generator) {
    console.error('usage: pnpm tsx rankings-engine/scripts/needs-human-issue.ts --triage <triage.json> --out <issue.md> --generator <name>')
    process.exit(1)
  }
  const triage = TriageReportSchema.parse(JSON.parse(fs.readFileSync(triagePath, 'utf8')))
  const body = buildNeedsHumanIssue(triage, generator)
  if (body === null) {
    console.log(`needs-human-issue: ${triagePath} holds no needs-human dispositions — ${out} not written, no issue to file`)
    return
  }
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, body + '\n')
  console.log(`needs-human-issue: wrote ${needsHumanRows(triage).length} needs-human row(s) to ${out}`)
}

if (require.main === module) {
  main(process.argv.slice(2))
}
